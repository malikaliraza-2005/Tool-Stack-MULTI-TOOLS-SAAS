"use client";

import { Command } from "cmdk";
import Fuse from "fuse.js";
import { CornerDownLeft, Download, FolderOpen, History, House, Star } from "lucide-react";
import { useRouter } from "next/navigation";
import { useEffect, useMemo, useState, type ReactNode } from "react";
import { ToolIcon } from "@/components/tool/ToolIcon";
import { Dialog, DialogContent } from "@/components/ui/Dialog";
import { Kbd } from "@/components/ui/Kbd";
import { commandItemClasses } from "@/components/ui/menu-styles";
import { cn } from "@/lib/cn";
import { CATEGORIES, CATEGORY_ORDER } from "@/tools/categories";
import { SEARCH_OPTIONS, searchTools, type SearchEntry } from "@/tools/search-index";
import { THEME_OPTIONS } from "./ThemeToggle";
import { promptInstall, useCanInstall } from "./useInstallPrompt";
import { setThemePreference } from "./useTheme";
import { useFavorites, useRecent } from "./useToolPrefs";

const groupClasses = cn(
  "[&_[cmdk-group-heading]]:px-2 [&_[cmdk-group-heading]]:pt-3 [&_[cmdk-group-heading]]:pb-1",
  "[&_[cmdk-group-heading]]:text-micro [&_[cmdk-group-heading]]:text-fg-muted [&_[cmdk-group-heading]]:uppercase",
);

// Fetched once per page load, on first open (generated by app/search-index.json).
let indexRequest: Promise<SearchEntry[]> | null = null;
function loadIndex(): Promise<SearchEntry[]> {
  indexRequest ??= fetch("/search-index.json").then((response) => {
    if (!response.ok) throw new Error(`search index: HTTP ${response.status}`);
    return response.json() as Promise<SearchEntry[]>;
  });
  // A failed request may succeed later (back online).
  indexRequest.catch(() => (indexRequest = null));
  return indexRequest;
}

type IndexState =
  { status: "loading" } | { status: "ready"; entries: SearchEntry[] } | { status: "error" };

function useSearchIndex(open: boolean): IndexState {
  const [state, setState] = useState<IndexState>({ status: "loading" });
  useEffect(() => {
    if (!open || state.status === "ready") return;
    let active = true;
    loadIndex().then(
      (entries) => active && setState({ status: "ready", entries }),
      () => active && setState({ status: "error" }),
    );
    return () => {
      active = false;
    };
  }, [open, state.status]);
  return state;
}

type PaletteCommand = {
  id: string;
  label: string;
  keywords: string[];
  icon: ReactNode;
  run: () => void;
};

const matches = (command: PaletteCommand, query: string) =>
  [command.label, ...command.keywords].some((text) => text.toLowerCase().includes(query));

type CommandPaletteProps = {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  onCloseAutoFocus: (event: Event) => void;
};

/**
 * ⌘K / Ctrl+K palette (design-system §8, G-1): fuzzy search over every tool
 * by name, synonym and accepted file type, plus favorites, recent tools,
 * hubs and the theme.
 */
export function CommandPalette({ open, onOpenChange, onCloseAutoFocus }: CommandPaletteProps) {
  const router = useRouter();
  const [query, setQuery] = useState("");
  const index = useSearchIndex(open);
  const favorites = useFavorites();
  const recent = useRecent();
  const canInstall = useCanInstall();

  const entries = index.status === "ready" ? index.entries : null;
  const fuse = useMemo(() => entries && new Fuse(entries, SEARCH_OPTIONS), [entries]);

  const run = (action: () => void) => {
    onOpenChange(false);
    action();
  };
  const go = (href: string) => run(() => router.push(href));

  const navigation: PaletteCommand[] = [
    {
      id: "home",
      label: "Home",
      keywords: ["start"],
      icon: <House aria-hidden />,
      run: () => go("/"),
    },
    ...CATEGORY_ORDER.map((category) => ({
      id: `hub:${category}`,
      label: CATEGORIES[category].name,
      keywords: ["category", "hub", "all"],
      icon: <FolderOpen aria-hidden />,
      run: () => go(CATEGORIES[category].href),
    })),
  ];
  const actions: PaletteCommand[] = [
    ...THEME_OPTIONS.map(({ value, label, icon: Icon }) => ({
      id: `theme:${value}`,
      label: `Theme: ${label}`,
      keywords: ["theme", "appearance", "mode", label.toLowerCase()],
      icon: <Icon aria-hidden />,
      run: () => run(() => setThemePreference(value)),
    })),
    // Only where the browser offers it (P7-T14); never shown as a pop-up.
    ...(canInstall
      ? [
          {
            id: "install",
            label: "Install Sprigkit as an app",
            keywords: ["install", "app", "offline", "pwa", "desktop"],
            icon: <Download aria-hidden />,
            run: () => run(() => void promptInstall()),
          },
        ]
      : []),
  ];

  const trimmed = query.trim().toLowerCase();
  const bySlug = new Map(entries?.map((entry) => [entry.slug, entry]));
  const pick = (slugs: string[]) => slugs.flatMap((slug) => bySlug.get(slug) ?? []);

  const toolItem = (entry: SearchEntry, prefix: string, icon?: ReactNode) => (
    <Command.Item
      key={`${prefix}:${entry.slug}`}
      value={`${prefix}:${entry.slug}`}
      onSelect={() => go(`/${entry.slug}`)}
      className={commandItemClasses}
    >
      {icon ?? <ToolIcon name={entry.icon} className="text-fg-muted" />}
      <span className="truncate">{entry.name}</span>
      <span className="ml-auto hidden shrink-0 text-small text-fg-muted sm:inline">
        {CATEGORIES[entry.category].name.replace(" tools", "")}
      </span>
    </Command.Item>
  );
  const commandItem = (command: PaletteCommand) => (
    <Command.Item
      key={command.id}
      value={command.id}
      onSelect={command.run}
      className={commandItemClasses}
    >
      <span className="text-fg-muted">{command.icon}</span>
      {command.label}
    </Command.Item>
  );
  const group = (heading: string, items: ReactNode[]) =>
    items.length > 0 && (
      <Command.Group heading={heading} className={groupClasses}>
        {items}
      </Command.Group>
    );

  let toolGroups: ReactNode;
  if (!entries) {
    toolGroups = (
      <p role="status" className="px-2 py-6 text-center text-small text-fg-muted">
        {index.status === "error"
          ? "The tool list couldn’t be loaded. Check your connection and try again."
          : "Loading tools…"}
      </p>
    );
  } else if (trimmed) {
    const found = fuse ? searchTools(fuse, trimmed, 8) : [];
    toolGroups = group(
      "Tools",
      found.map((entry) => toolItem(entry, "tool")),
    );
  } else {
    toolGroups = (
      <>
        {group(
          "Favorites",
          pick(favorites).map((entry) =>
            toolItem(entry, "favorite", <Star aria-hidden className="text-accent-text" />),
          ),
        )}
        {group(
          "Recent",
          pick(recent).map((entry) =>
            toolItem(entry, "recent", <History aria-hidden className="text-fg-muted" />),
          ),
        )}
        {CATEGORY_ORDER.map((category) => (
          <Command.Group
            key={category}
            heading={CATEGORIES[category].name}
            className={groupClasses}
          >
            {entries
              .filter((entry) => entry.category === category)
              .map((entry) => toolItem(entry, "tool"))}
          </Command.Group>
        ))}
      </>
    );
  }

  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent
        title="Search tools and actions"
        hideTitle
        hideClose
        placement="top"
        width="palette"
        bare
        onCloseAutoFocus={onCloseAutoFocus}
        // Start empty on every open. Clearing it on close instead re-renders the
        // list during the theme View Transition, which crashed WebKit.
        onOpenAutoFocus={() => setQuery("")}
      >
        <Command loop shouldFilter={false} label="Search tools and actions">
          <Command.Input
            value={query}
            onValueChange={setQuery}
            placeholder="Search tools and actions…"
            className="h-12 w-full border-b border-border bg-transparent px-4 text-body text-fg outline-none placeholder:text-fg-subtle"
          />
          <Command.List className="max-h-(--sheet-max-height) overflow-y-auto p-2 sm:max-h-96">
            {entries && (
              <Command.Empty className="px-2 py-6 text-center text-small text-fg-muted">
                Nothing matches “{query.trim()}”. Try “PDF”, “compress”, “HEIC” or “JSON”.
              </Command.Empty>
            )}
            {toolGroups}
            {group(
              "Go to",
              navigation
                .filter((command) => !trimmed || matches(command, trimmed))
                .map(commandItem),
            )}
            {group(
              "Actions",
              actions.filter((command) => !trimmed || matches(command, trimmed)).map(commandItem),
            )}
          </Command.List>
          <div className="hidden items-center gap-4 border-t border-border px-4 py-2 text-small text-fg-muted sm:flex">
            <span className="inline-flex items-center gap-1">
              <Kbd>↑</Kbd>
              <Kbd>↓</Kbd> to move
            </span>
            <span className="inline-flex items-center gap-1">
              <Kbd>
                <CornerDownLeft aria-hidden className="size-3" />
                <span className="sr-only">Enter</span>
              </Kbd>
              to select
            </span>
            <span className="inline-flex items-center gap-1">
              <Kbd>Esc</Kbd> to close
            </span>
          </div>
        </Command>
      </DialogContent>
    </Dialog>
  );
}
